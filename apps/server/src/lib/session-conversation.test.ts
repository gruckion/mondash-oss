test("only the last turns are sent, a long turn is clipped, and older turns go to stay under the size limit", () => {
  const many = Array.from({ length: TURN_LIMIT + 6 }, (_, i) =>
    i % 2 ? assistant(`answer ${i}`) : user(`prompt ${i}`),
  );
  const recent = conversation("claude", many);
  assert.equal(recent.turns.length, TURN_LIMIT);
  assert.equal(recent.turns.at(-1)?.text, `answer ${TURN_LIMIT + 5}`);
  assert.equal(recent.truncated, true);

  const long = conversation("claude", [
    user(`start${"a".repeat(TURN_TEXT_LIMIT)}`),
    assistant(`${"b".repeat(TURN_TEXT_LIMIT)}end`),
  ]);
  const [prompt, answer] = long.turns;
  assert.equal(prompt?.text.length, TURN_TEXT_LIMIT);
  assert.ok(prompt?.text.startsWith("start") && prompt.text.endsWith("…"));
  assert.equal(answer?.text.length, TURN_TEXT_LIMIT);
  assert.ok(answer?.text.startsWith("…") && answer.text.endsWith("end"));

  const big = Array.from({ length: 20 }, (_, i) => (i % 2 ? assistant : user)(`${"c".repeat(TURN_TEXT_LIMIT)} ${i}`));
  const capped = conversation("claude", big);
  const bytes = capped.turns.reduce((sum, turn) => sum + new TextEncoder().encode(turn.text).length, 0);
  assert.ok(bytes <= TOTAL_LIMIT);
  assert.ok(capped.turns.at(-1)?.text.endsWith(" 19"));
  assert.equal(capped.truncated, true);
});

