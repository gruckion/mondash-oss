test("Claude pasted content stays readable and embedded images remain previewable, including image-only prompts", async () => {
  const data = "UklGRg==";
  const image = { type: "image", source: { type: "base64", media_type: "image/webp", data } };
  const sources = new Map<string, AttachmentSource>();
  const result = conversation(
    "claude",
    [
      user([
        image,
        {
          type: "text",
          text: 'Please check this.\n\n<pasted_content id="65a6">\nThe **SDK** changed.\n\nSee https://github.com/example/app/pull/1\n</pasted_content id="65a6">\n\nExplain it.',
        },
      ]),
      user([{ type: "text", text: '<pasted_content id="next">\n<div>Hello</div>\n</pasted_content>' }], 1),
      user([image], 2),
      user([image], 3, { isMeta: true }),
      user([{ type: "image", source: { type: "url", url: "https://example.com/image.png" } }], 4),
      assistant('The literal `<pasted_content id="example">` is an XML tag.', 5),
    ],
    sources,
  );
  assert.equal(result.turns.length, 4);
  assert.equal(
    result.turns[0]?.text,
    "Please check this.\n\nThe **SDK** changed.\n\nSee https://github.com/example/app/pull/1\n\nExplain it.",
  );
  assert.equal(result.turns[1]?.text, "<div>Hello</div>");
  assert.equal(result.turns[2]?.text, "");
  assert.equal(result.turns[3]?.text, 'The literal `<pasted_content id="example">` is an XML tag.');
  for (const index of [0, 2]) {
    const attachments = result.turns[index]?.attachments;
    assert.equal(attachments?.length, 1);
    assert.equal(attachments?.[0]?.kind, "image");
    const source = sources.get(attachments![0]!.id);
    assert.ok(source);
    assert.deepEqual(await readAttachment(source), { name: "Image 1", mediaType: "image/webp", data });
  }
  assert.ok(!JSON.stringify(result).includes(data));
});

