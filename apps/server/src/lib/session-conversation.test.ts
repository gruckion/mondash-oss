import assert from "node:assert/strict";
import { test } from "node:test";
import { readAttachment, type AttachmentSource } from "./session-attachments";
import { conversation, TOTAL_LIMIT, TURN_LIMIT, TURN_TEXT_LIMIT } from "./session-conversation.ts";

const at = (minute: number) => `2026-09-24T20:${String(minute).padStart(2, "0")}:00.000Z`;
const user = (content: unknown, minute = 0, extra = {}) => ({
  type: "user",
  timestamp: at(minute),
  message: { content },
  ...extra,
});
const assistant = (text: string, minute = 0, extra = {}) => ({
  type: "assistant",
  timestamp: at(minute),
  message: { content: [{ type: "text", text }] },
  ...extra,
});
const codex = (role: string, text: string, extra = {}) => ({
  type: "response_item",
  timestamp: at(0),
  payload: {
    type: "message",
    role,
    content: [{ type: role === "assistant" ? "output_text" : "input_text", text }],
    ...extra,
  },
});

test("a Claude conversation keeps prompts and answers as Markdown, without tool use, sub-agents or injected text", () => {
  const result = conversation("claude", [
    { type: "system", subtype: "away_summary", content: "A recap" },
    user("<command-name>/clear</command-name>"),
    user("Fix the **build**", 1),
    assistant("Looking at `ci.yml`.", 2),
    { type: "assistant", message: { content: [{ type: "tool_use", name: "Bash", input: {} }] } },
    user([{ type: "tool_result", content: "npm ERR!" }]),
    user("Caveat: the messages below were generated by the user", 3, { isMeta: true }),
    assistant("Sub-agent notes", 3, { isSidechain: true }),
    user("Summary of the earlier conversation", 3, { isCompactSummary: true }),
    user([{ type: "text", text: "[Request interrupted by user for tool use]" }]),
    assistant("## Fixed\n\n- The lockfile was stale.", 4),
    user([
      { type: "text", text: "<system-reminder>be brief</system-reminder>" },
      { type: "text", text: "Thanks" },
    ]),
  ]);
  assert.deepEqual(result, {
    turns: [
      { role: "user", text: "Fix the **build**", at: at(1) },
      { role: "assistant", text: "Looking at `ci.yml`.\n\n## Fixed\n\n- The lockfile was stale.", at: at(4) },
      { role: "user", text: "Thanks", at: at(0) },
    ],
    truncated: false,
  });
});

