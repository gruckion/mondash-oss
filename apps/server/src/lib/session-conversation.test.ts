test("a command-heavy Codex run keeps its prompt and stable message identity within the payload budget", () => {
  const prompt = codex("user", "Keep my request visible");
  const commands = Array.from({ length: 40 }, (_, i) => [
    {
      type: "response_item",
      payload: { type: "function_call", name: "exec_command", arguments: '{"cmd":"bun test"}', call_id: String(i) },
    },
    {
      type: "response_item",
      payload: { type: "function_call_output", output: "x".repeat(16_000), call_id: String(i) },
    },
  ]).flat();
  const first = conversation("codex", [prompt]);
  const busy = conversation("codex", [prompt, ...commands]);
  assert.equal(busy.turns[0]?.text, "Keep my request visible");
  assert.equal(busy.turns[0]?.id, first.turns[0]?.id);
  assert.equal(busy.turns.filter((turn) => turn.activity).length, 40);
  const bytes = busy.turns.reduce(
    (size, turn) =>
      size + new TextEncoder().encode(turn.text + (turn.activity?.input ?? "") + (turn.activity?.output ?? "")).length,
    0,
  );
  assert.ok(bytes <= TOTAL_LIMIT);
  assert.equal(busy.truncated, true);
  assert.equal(busy.turns.at(-1)?.activity?.output?.length, 16_000);
});

